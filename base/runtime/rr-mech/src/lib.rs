//! # rr-mech —— 机制核切片：控制原语与安全核
//!
//! 承 ADR-0018 裁定 5：控制原语与安全核是不读墙上时钟、不睡眠、时钟与输入由外部
//! 注入的纯计算——同一张控制图在实时环里跑、在裸机定时器里跑，行为逐拍一致；且
//! 安全核不可被策略改写，永远包住任何控制图。件面是 [`control`]：限速门 / 低电
//! 边沿 / 饱和检测 / 限位钳位四件原语。
//! 本 crate 是机制核切片里的零依赖叶子件：整模块自 `rr-core::control` 逐字迁入，
//! `rr-core` 以 `pub use rr_mech::control;` re-export，既有 `rr_core::control::*`
//! 引用点逐字不变。板档固件需要直接消费判定核（安全核离线仍须成立），而 `rr-core`
//! 背负总线语义栈（依赖 `rr-ipc`）——切成叶子件后板档可按需引入而不被牵连。
//!
//! 零策略载荷：不得出现厂商名 / 产品名 / 业务阈值 / 器件名条件分支（§13 门禁），
//! 也不依赖任何其它 crate（core+alloc 可达），是该纪律的最简可证面。

#![no_std]

