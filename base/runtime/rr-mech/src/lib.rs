//! # rr-mech —— 机制核切片：控制原语与安全核
//!
//! 承 [ADR-0018](../../../docs/process/adr/ADR-0018-跨操作系统移植-机制核与主承载层分离.md)
//! 裁定 5：控制原语与安全核是不读墙上时钟、不睡眠、时钟与输入由外部注入的
//! **纯计算**——同一张控制图在实时环里跑、在裸机定时器里跑，行为逐拍一致；
//! 且安全核不可被策略改写，永远包住任何控制图。
//!
//! 本 crate 是**机制核切片**中的叶子件：整模块自 `rr-core::control` 逐字迁入
//! （下沉，路径与语义零漂移），`rr-core` 以 `pub use rr_mech::control;`
//! re-export，使既有 `rr_core::control::*` 引用点**逐字不变**、消费面零波及。
//! 下沉动机：板档固件需要直接消费判定核（安全核离线仍须成立），而 `rr-core`
//! 背负总线语义栈（依赖 `rr-ipc`）——把控制原语切成零依赖叶子件，板档即可按需
//! 引入本 crate 而不被总线栈牵连（机制核与承载层的可组合点）。
//!
//! - [`control`]：限速门 / 低电边沿 / 饱和检测 / 限位钳位四件原语。
//!
//! 零策略载荷：不得出现厂商名 / 产品名 / 业务阈值 / 器件名条件分支
//! （architecture §13 门禁，批E 接线——门禁 grep 自身禁词，本行以中文表述自指）。
//! 本 crate 不依赖任何其它 crate（core+alloc 可达），是该纪律的最简可证面。

