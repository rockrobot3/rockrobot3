//! periph-mech —— 外设机制核（P0-A，骨架轨与板侧后端的共同前置）。
//!
//! ## 为什么单独成 crate
//!
//! 帧面收发、OLED 编码、舵机缓速/轨压拒动、轨压双阈值判定都是**平台无关机制**：
//! 换平台（各芯片档 / 单板机 / 仿真）只换五端口实现（
//! [`rr_periph_proto::ports`]），这四件零改动。此前它们与驱动共用同一 crate，
//! 换平台等于整份抄一遍——本 crate 把机制面析出，适配层只剩驱动构造与线程。
//!
//! ## 边界纪律
//!
//! - **零 esp-idf 依赖**：宿主与板档双向引用本 crate，任何平台依赖都会污染另一侧
//!   构建面（ADR-0024，与 `rr-periph-proto` 同一条纪律）。
//! - **不读墙上时钟、不睡眠、不持线程**：时序与随机由适配层注入；机制只算。
//! - **零策略量**：阈值/行程/亮度阶梯/步进/引脚一律按参传入，本 crate 不写板名。
//! - 不搬驱动构造、控制/运行线程、`httpd`、`mic`——它们归各平台适配层。
//!
//! ## 模块
//!
//! - [`frame`]：帧面收帧/应答（泛型于 UART/时钟端口）；
//! - [`oled_codec`]：128×64 页寻址 OLED 的纯编码（字模/文本页/点阵页/初始化序）；
//! - [`periph_core`]：舵机行程校验与缓速步进、轨压拒动、亮度降档阶梯；
//! - [`rail_judge`]：轨压分压换算 + 双阈值电平分类 + 迟滞边沿事件。

pub mod frame;
pub mod oled_codec;
pub mod periph_core;
pub mod rail_judge;
