/// 可见 ASCII 取字模（其余一律空格字形——fail-closed，不越表下标）。
pub fn rr3_glyph(c: u8) -> [u8; 5] {
    let idx = match c {
        0x20..=0x7E => (c - 0x20) as usize,
        _ => 0,
    };
    RR3_FONT5X7[idx]
}

// ---------------------------------------------------------------------------
// 页缓冲编码
// ---------------------------------------------------------------------------

/// 文本行 → 单页缓冲（行号 `row` 映射页 `row*2`；每字符 5px 字模 + 1px 空列）。
/// `cols` 为每行字符数上限（超出截断），`rows` 为合法行数上限（越界点名回 Err
/// ——fail-closed，不静默落页）。
pub fn rr3_text_page(
    row: usize,
    text: &[u8],
    rows: usize,
    cols: usize,
) -> Result<[u8; RR3_OLED_PAGE_BYTES], String> {
    if row >= rows {
        return Err(format!("文本行号越界: {row}"));
    }
    let mut buf = RR3_OLED_ZERO_PAGE;
    let mut col = 0usize;
    for &c in text.iter().take(cols) {
        if col + 6 > RR3_OLED_PAGE_BYTES {
            break;
        }
        buf[col..col + 5].copy_from_slice(&rr3_glyph(c));
        col += 6;
    }
    Ok(buf)
}

/// 8×8 点阵帧 → 8 页缓冲（中央 64×64 放大）：源帧每像素横向铺 8 列、纵向铺 8 行，
/// 落在列 32..96 × 全 8 页；页 p 全部 8 个位行同显源行 p。位序映射：源字节
/// bit7 = 行最左 ↔ 目标列 x=32 处——方向不镜像；页内列字节 bit0 = 页顶。
/// 两侧留白清零（居中不残影）。
pub fn rr3_frame_pages(frame: &[u8; 8]) -> [[u8; RR3_OLED_PAGE_BYTES]; 8] {
    let mut pages = [RR3_OLED_ZERO_PAGE; 8];
    for (page, buf) in pages.iter_mut().enumerate() {
        let src = frame[page];
        for (x, cell) in buf.iter_mut().enumerate().skip(32).take(64) {
            let c = (x - 32) / 8;
            *cell = if (src >> (7 - c)) & 1 == 1 { 0xFF } else { 0 };
        }
    }
    pages
}

/// 页地址命令（页寻址模式三字节：页号 + 列低/高四位清零；每次整页从确定性起点写）。
pub fn rr3_page_cmd(page: u8) -> [u8; 3] {
    [0xB0 | page, 0x00, 0x10]
}

/// 初始化命令序（面板数据手册标准序；`contrast` 由策略面按当前档传入）。
pub fn rr3_init_commands(contrast: u8) -> [u8; 25] {
    [
        0xAE, // display off
        0xD5, 0x80, // clock div
        0xA8, 0x3F, // multiplex 64
        0xD3, 0x00, // display offset
        0x40, // start line 0
        0x8D, 0x14, // charge pump on
        0x20, 0x02, // page addressing mode
        0xA1, // segment remap
        0xC8, // COM scan dec
        0xDA, 0x12, // COM pins
        0x81, contrast, // contrast
        0xD9, 0xF1, // precharge
        0xDB, 0x40, // VCOM detect
        0xA4, // resume from RAM
        0xA6, // normal display
        0xAF, // display on
    ]
}

/// 亮度命令（`0x81` + 档值）。
pub fn rr3_contrast_command(level: u8) -> [u8; 2] {
    [0x81, level]
}

/// 文本 3 行 + 角度行排版（纯计算）：非可见 ASCII 一律折空格后按 `cols` 列硬切，
/// 最后一行为固定角度行（`P:ddd T:ddd`）。不劈多字节字符（先按 char 过滤再切）。
pub fn rr3_oled_lines(
    text: &str,
    pan_deg: u32,
    tilt_deg: u32,
    rows: usize,
    cols: usize,
) -> Vec<Vec<u8>> {
    let ascii: Vec<u8> = text
        .chars()
        .map(|c| {
            if (0x20..=0x7E).contains(&(c as u32)) {
                c as u8
            } else {
                b' '
            }
        })
        .collect();
    let mut lines: Vec<Vec<u8>> = Vec::with_capacity(rows);
    for row in 0..rows.saturating_sub(1) {
        let start = row * cols;
        lines.push(if start < ascii.len() {
            ascii[start..(start + cols).min(ascii.len())].to_vec()
        } else {
            Vec::new()
        });
    }
    lines.push(format!("P:{pan_deg:03} T:{tilt_deg:03}").into_bytes());
    lines
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyph_is_bounded_and_fail_closed() {
        assert_eq!(rr3_glyph(b' '), [0x00, 0x00, 0x00, 0x00, 0x00]);
        assert_eq!(rr3_glyph(b'A'), [0x7E, 0x11, 0x11, 0x11, 0x7E]);
        // 表外字节（含控制符与高位）一律空格字形，不越界
        assert_eq!(rr3_glyph(0x01), rr3_glyph(b' '));
        assert_eq!(rr3_glyph(0xC8), rr3_glyph(b' '));
        assert_eq!(rr3_glyph(b'~'), RR3_FONT5X7[94]);
    }

    #[test]
    fn text_page_rejects_row_and_places_glyph() {
        assert_eq!(
            rr3_text_page(4, b"X", 4, 21).unwrap_err(),
            "文本行号越界: 4"
        );
        let page = rr3_text_page(0, b"A", 4, 21).expect("行内");
        assert_eq!(&page[0..6], &[0x7E, 0x11, 0x11, 0x11, 0x7E, 0x00]);
        assert!(page[6..].iter().all(|&b| b == 0));
        // 每行字符数上限（21 列）硬截断：22 字符只落前 21 个
        let full = rr3_text_page(0, &[b'A'; 22], 4, 21).expect("行内");
        assert_eq!(full[20 * 6], 0x7E);
        assert!(full[21 * 6..].iter().all(|&b| b == 0));
    }

    #[test]
    fn frame_pages_center_scale_mapping() {
        let mut frame = [0u8; 8];
        frame[0] = 0x80; // 页 0 源行最左像素（bit7）
        let pages = rr3_frame_pages(&frame);
        // 列 32..40 全亮（一个源像素铺 8 列），两侧留白
        assert!(pages[0][32..40].iter().all(|&b| b == 0xFF));
        assert!(pages[0][..32].iter().all(|&b| b == 0));
        assert!(pages[0][96..].iter().all(|&b| b == 0));
        assert!(pages[0][40..96].iter().all(|&b| b == 0));
        // 其余页源字节为零 → 全零
        for (p, page) in pages.iter().enumerate().skip(1) {
            assert!(page.iter().all(|&b| b == 0), "页 {p} 应全零");
        }
    }

    #[test]
    fn init_and_contrast_command_shapes() {
        let cmds = rr3_init_commands(0x4F);
        assert_eq!(cmds.len(), 25);
        assert_eq!(cmds[16], 0x81, "亮度命令前导");
        assert_eq!(cmds[17], 0x4F, "亮档次位置");
        assert_eq!(cmds[24], 0xAF, "末字节 display on");
        assert_eq!(rr3_contrast_command(0x2F), [0x81, 0x2F]);
        assert_eq!(rr3_page_cmd(3), [0xB3, 0x00, 0x10]);
    }

    #[test]
    fn oled_lines_wrap_and_append_angle_row() {
        let rows = rr3_oled_lines("0123456789ABCDEFGHIJKLMNOPQRST", 90, 80, 4, 21);
        assert_eq!(rows.len(), 4);
        assert_eq!(rows[0], b"0123456789ABCDEFGHIJK");
        assert_eq!(rows[1], b"LMNOPQRST");
        assert!(rows[2].is_empty());
        assert_eq!(rows[3], b"P:090 T:080");
        // 非 ASCII 折空格，不劈字符
        let zh = rr3_oled_lines("中A", 0, 0, 4, 21);
        assert_eq!(zh[0], b" A");
    }
}
