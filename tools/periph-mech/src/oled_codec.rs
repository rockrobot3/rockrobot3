//! OLED 纯编码机制（P0-A A2 自板档适配层迁入）——128×64、页寻址控制器。
//!
//! 本模块只产出**页缓冲**与**命令序列字节**：字模、文本行排版、8×8 点阵放大、
//! 初始化序、亮度命令。真正的 I2C 事务、分块、重试与总线自愈全在适配层
//! （它们操作平台驱动/引脚，不是编码）；策略量（每页字符数、行数、初始亮度）
//! 一律按参传入。

/// 单页字节数（128 列 × 8 行，页内 bit0 = 页顶）。
pub const RR3_OLED_PAGE_BYTES: usize = 128;

/// 全零页（清屏页；页写缓冲的确定性起点）。
pub const RR3_OLED_ZERO_PAGE: [u8; RR3_OLED_PAGE_BYTES] = [0u8; RR3_OLED_PAGE_BYTES];

